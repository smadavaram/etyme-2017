import { directorySignIn, json, say } from './walk.mjs'
const ines = await directorySignIn('ines.okafor@northbend.example', 'nb-0001')
say('Ines directory sign-in:', JSON.stringify({ ok: ines.ok, refused: ines.refused, status: ines.status, land: ines.land }))
const ov = await json(ines.jar, '/api/settings/sign-in/overview')
say('Ines overview:', ov.status, ov.body?.data?.effective, ov.body?.error?.message ?? '')
const p = await json(ines.jar, '/api/settings/sign-in', { method: 'PATCH', body: JSON.stringify({ mode: 'SSO_ONLY', reason: 'Demo walk: directory only', jit: true, scim: true }) })
say('Ines sets SSO_ONLY:', p.status, p.body?.data?.effective ?? p.body?.error?.message)
const ov2 = await json(ines.jar, '/api/settings/sign-in/overview')
say('Ines overview after:', ov2.status, ov2.body?.data?.effective)
const m = await directorySignIn('mateo.silva@northbend.example', 'nb-0002')
say('Mateo directory sign-in:', JSON.stringify({ ok: m.ok, refused: m.refused }))
const me = await json(m.jar, '/api/me')
say('Mateo /api/me:', me.status, JSON.stringify(me.body?.data?.context ?? me.body?.data?.seat ?? Object.keys(me.body?.data ?? {})).slice(0, 200))
const req = await json(m.jar, '/api/requirements')
say('Mateo /api/requirements:', req.status, Array.isArray(req.body?.data) ? `${req.body.data.length} rows` : (req.body?.error?.message ?? ''))
const mo = await json(m.jar, '/api/settings/sign-in/overview')
say('Mateo overview (not Owner/Admin):', mo.status, mo.body?.error?.message)
const tk = await json(ines.jar, '/api/settings/sign-in/scim', { method: 'POST' })
say('SCIM token issued:', tk.status, tk.body?.data?.token ? 'shown once' : tk.body?.error?.message)
const T = tk.body?.data?.token
const H = { authorization: `Bearer ${T}`, 'content-type': 'application/scim+json' }
let r = await fetch(`http://localhost:3123/scim/v2/Users?filter=${encodeURIComponent('userName eq "mateo.silva@northbend.example"')}`, { headers: H })
const list = await r.json()
say('SCIM list by userName:', r.status, list.totalResults)
const id = list.Resources?.[0]?.id
r = await fetch(`http://localhost:3123/scim/v2/Users/${id}`, { method: 'PATCH', headers: H, body: JSON.stringify({ schemas: ['urn:ietf:params:scim:api:messages:2.0:PatchOp'], Operations: [{ op: 'replace', path: 'active', value: false }] }) })
const pj = await r.json()
say('SCIM deactivate Mateo:', r.status, 'active=', pj.active)
const after = await json(m.jar, '/api/requirements')
say('Mateo next request after SCIM deactivate:', after.status, after.body?.error?.message ?? '')
const again = await directorySignIn('mateo.silva@northbend.example', 'nb-0002')
say('Mateo signs in again through the directory:', JSON.stringify({ ok: again.ok, refused: again.refused?.slice?.(0, 120) }))
r = await fetch(`http://localhost:3123/scim/v2/Users?filter=${encodeURIComponent('userName eq "ines.okafor@northbend.example"')}`, { headers: H })
const ilist = await r.json()
r = await fetch(`http://localhost:3123/scim/v2/Users/${ilist.Resources?.[0]?.id}`, { method: 'DELETE', headers: H })
say('SCIM delete Ines (an Owner):', r.status, (await r.json().catch(() => ({}))).detail ?? '')
const bad = await fetch('http://localhost:3123/scim/v2/Users', { headers: { authorization: 'Bearer etyme_scim_guess' } })
say('SCIM with a guessed token:', bad.status)
// JIT
const nw = await directorySignIn('rosa.lindqvist@northbend.example', null, { name: 'Rosa Lindqvist', email: 'rosa.lindqvist@northbend.example', group: 'nb-hiring-managers' })
say('New person, just-in-time:', JSON.stringify({ ok: nw.ok, refused: nw.refused }))
const nme = await json(nw.jar, '/api/requirements')
say('Rosa /api/requirements:', nme.status)
process.stdout.write('\nTOKEN=' + T + '\n')
