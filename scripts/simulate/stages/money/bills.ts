/**
 * Stage: bills. Owned by money.
 *
 * Each firm bills the firm above it on the weeks that firm signed: the
 * supplier at the top bills the client once the client has signed, and
 * a supplier lower down bills the firm above it once that firm has
 * accepted the week — never waiting on the rungs below. Through the Bills
 * page's own generator (`POST /api/invoices/generate`), one bill per
 * billing period of the agreement between the two (one bill covers one
 * billing period), then sent (`POST /api/invoices/:id/submit`).
 *
 * First the nightly job runs, because the supplier's twin drafts a bill
 * on the agreement's billing date for every placement whose period has
 * ended, and asks whoever sends bills for a yes. Those drafts are
 * answered in the one approval route the web and Teams share; what the
 * twin did not draft is generated by hand.
 *
 * Checked after, against the record: a bill on a rung below the top
 * prices the hours the firm above accepted, not the hours worked.
 *
 * Karthik Menon's case: a placement that ended with signed weeks nobody
 * billed. The generator read only running placements, so fourteen signed
 * weeks could never be billed. Each ended placement with signed weeks
 * left is billed here, period by period.
 *
 * And the rule held on purpose: a bill for a week the client has not
 * signed is refused, and the refusal names who it is waiting on.
 */
import { defineStage, type BillFact } from '../../stage'
import type { Actor } from '../../actors'
import { ORDER_HEADER_SELECT, AGREEMENT_TERMS_SELECT, periodTermsFor } from '@/lib/money/order-terms'
import { billingStraddle, periodFor, type Period } from '@/lib/periods'
import {
  placementsOf, seatWith, keyedByEmail, payerSigned, weekExtra, centsOf, dollars, iso, says,
  type Placement, type Rung,
} from './book'

interface Due { rung: Rung; period: Period; placement: Placement }

export default defineStage({
  name: 'bills',
  domain: 'MONEY',
  async run(ctx) {
    const { placements, endedUnbilled } = await placementsOf(ctx)

    // Karthik Menon's case, measured before anything is billed: each ended
    // placement's signed weeks that no bill carries yet.
    const owedOnEnded = new Map<string, { name: string; ids: string[]; cents: number }>()
    for (const p of endedUnbilled.filter((x) => x.ladder.length === 1)) {
      const sheets = await ctx.read.timesheet.findMany({
        where: {
          sellContractId: p.id,
          assertions: { some: { role: 'CLIENT_APPROVAL', state: 'LIVE' } },
          invoiceLines: { none: { sellContractId: p.id } },
        },
        select: { id: true, totalHours: true },
      })
      if (sheets.length === 0) continue
      owedOnEnded.set(p.id, {
        name: p.personName,
        ids: sheets.map((t) => t.id),
        cents: Math.round(sheets.reduce((n, t) => n + Number(t.totalHours), 0) * p.bottom.billRate),
      })
    }

    // ── The twin's drafts, answered first ───────────────────────────────
    await ctx.cast.cron('twin')
    const engagements = new Set(
      [...placements, ...endedUnbilled].flatMap((p) => p.ladder.map((r) => r.engagementId)).filter(Boolean) as string[]
    )
    const keyedEngagements = new Set(
      placements.filter((p) => keyedByEmail(placements, p)).map((p) => p.bottom.engagementId).filter(Boolean) as string[]
    )
    const asks = await ctx.read.twinApproval.findMany({
      where: { decision: 'PENDING', needsPermission: 'invoices.issue', twinAction: { entityType: 'Invoice' } },
      select: { id: true, companyId: true, twinAction: { select: { entityId: true, authorityPersonId: true } } },
    })
    const drafts = await ctx.read.invoice.findMany({
      where: { id: { in: asks.map((a) => a.twinAction.entityId) }, status: 'DRAFT' },
      select: { id: true, engagementId: true },
    })
    let twinSent = 0
    await ctx.parallel(asks, async (a) => {
      const d = drafts.find((x) => x.id === a.twinAction.entityId)
      if (!d || !engagements.has(d.engagementId) || keyedEngagements.has(d.engagementId)) return
      const avoid = a.twinAction.authorityPersonId ? [a.twinAction.authorityPersonId] : []
      // Whoever else sends bills says yes; where nobody else does, the
      // Owner may (the founder, 2026-10-19, decision 2).
      const seat = (await seatWith(ctx, a.companyId, 'invoices.issue', avoid)) ?? (await seatWith(ctx, a.companyId, 'invoices.issue'))
      if (!seat) return
      const res = await seat.post(`/api/twin/approvals/${a.id}`, { decision: 'APPROVED' })
      if (res.ok) twinSent++
    })

    // ── What each rung may bill, by billing period ──────────────────────
    const rungIds = [...new Set(placements.flatMap((p) => p.ladder.map((r) => r.sellId)))]
    const lines = await ctx.read.sellContract.findMany({
      where: { id: { in: [...rungIds, ...endedUnbilled.map((p) => p.id)] } },
      select: {
        id: true, startDate: true, endDate: true, billFrequency: true, billAnchor: true, billStraddle: true,
        paymentTerms: true, paymentTermsFrom: true, billCurrency: true, termsDifferReason: true,
        workOrder: { select: ORDER_HEADER_SELECT }, msa: { select: AGREEMENT_TERMS_SELECT },
      },
    })
    const periodOf = (sellId: string, days: Record<string, number>): Period | null => {
      const line = lines.find((l) => l.id === sellId)
      if (!line) return null
      const terms = periodTermsFor('SELL', line)
      const worked = Object.entries(days).filter(([, h]) => Number(h) > 0).map(([d]) => d.slice(0, 10)).sort()
      if (!worked.length) return null
      const on = billingStraddle(terms.straddle).straddle === 'START' ? worked[0] : worked[worked.length - 1]
      return periodFor(new Date(`${on}T00:00:00Z`), terms)
    }

    // What is already on a bill, the twin's included: a week bills once per rung.
    const onBills = new Set(
      (
        await ctx.read.invoiceLine.findMany({
          where: { timesheetId: { in: ctx.world.weeks.map((w) => w.id) } },
          select: { timesheetId: true, sellContractId: true },
        })
      ).map((l) => `${l.timesheetId}/${l.sellContractId}`)
    )
    const due = new Map<string, Due>()
    // A bill is raised on the agreement's date, the day after its billing
    // period ends; a period still running waits for its end.
    const today = Date.parse(`${iso(Date.now())}T00:00:00Z`)
    const notYet = new Set<string>()
    const plan = (rung: Rung, period: Period | null, p: Placement) => {
      if (!period) return
      const key = `${rung.sellId}/${iso(period.start)}`
      if (period.end.getTime() >= today) {
        notYet.add(key)
        return
      }
      due.set(key, { rung, period, placement: p })
    }
    for (const w of ctx.world.weeks) {
      const x = weekExtra(w)
      const p = placements.find((q) => q.id === w.contractId)
      if (!p) continue
      p.ladder.forEach((rung, i) => {
        if (!rung.engagementId || !payerSigned(p, i, x)) return
        if (i === p.ladder.length - 1 && keyedByEmail(placements, p)) return
        if (onBills.has(`${w.id}/${rung.sellId}`)) return
        const period = periodOf(rung.sellId, x.days)
        plan(rung, period, p)
      })
    }

    // An expense every firm above accepted bills in the period it was spent in.
    const expenseOnBills = new Set(
      (
        await ctx.read.invoiceLine.findMany({
          where: { expenseId: { in: ctx.world.expenses.map((e) => e.id) } },
          select: { expenseId: true, sellContractId: true },
        })
      ).map((l) => `${l.expenseId}/${l.sellContractId}`)
    )
    for (const e of ctx.world.expenses.filter((x) => x.status === 'ACCEPTED')) {
      const p = placements.find((q) => q.id === e.contractId)
      const end = String(e.extra?.periodEnd ?? '')
      if (!p || !end) continue
      for (const rung of p.ladder) {
        if (!rung.engagementId || expenseOnBills.has(`${e.id}/${rung.sellId}`)) continue
        if (rung === p.bottom && keyedByEmail(placements, p)) continue
        const period = periodOf(rung.sellId, { [end]: 1 })
        plan(rung, period, p)
      }
    }

    // Karthik's case: ended placements with signed weeks no bill carries.
    const ended: Due[] = []
    for (const p of endedUnbilled) {
      if (!p.bottom.engagementId) continue
      const sheets = await ctx.read.timesheet.findMany({
        where: {
          sellContractId: p.id,
          assertions: { some: { role: 'CLIENT_APPROVAL', state: 'LIVE' } },
          invoiceLines: { none: { sellContractId: p.id } },
        },
        select: { days: true },
      })
      // Only where the employer bills the client directly; a chain's ended top rung is billed the same way above.
      if (p.ladder.length !== 1) continue
      const seen = new Set<string>()
      for (const s of sheets) {
        const period = periodOf(p.id, (s.days ?? {}) as Record<string, number>)
        if (!period || seen.has(iso(period.start))) continue
        seen.add(iso(period.start))
        ended.push({ rung: p.bottom, period, placement: p })
      }
    }

    let made = 0
    let sent = 0
    let totalCents = 0
    let endedCents = 0
    let endedBills = 0
    const bill = async (d: Due, isEnded: boolean) => {
      const seat: Actor | null = await seatWith(ctx, d.rung.sellerId, 'invoices.issue', [d.placement.personId])
      if (!seat) return
      const res = await seat.post('/api/invoices/generate', {
        engagementId: d.rung.engagementId, periodStart: iso(d.period.start), periodEnd: iso(d.period.end),
      })
      const inv = res.json?.data?.invoice
      if (!res.ok || !inv?.id) return
      made++
      const fact: BillFact = {
        id: inv.id, by: seat.key, fromSlug: d.rung.sellerSlug, toSlug: d.rung.buyerSlug,
        totalCents: centsOf(inv.total ?? 0), status: 'ISSUED',
        extra: { placementId: d.placement.id, sellId: d.rung.sellId, period: d.period.label, ended: isEnded },
      }
      ctx.world.bills.push(fact)
      const out = await seat.post(`/api/invoices/${inv.id}/submit`)
      if (out.ok) {
        sent++
        fact.status = 'SUBMITTED'
      }
      if (isEnded) {
        endedBills++
        endedCents += fact.totalCents
      }
    }
    // One bill at a time per engagement, oldest period first, as a person
    // works down the Bills page; engagements side by side.
    const byEngagement = (list: { d: Due; ended: boolean }[]) => {
      const m = new Map<string, { d: Due; ended: boolean }[]>()
      for (const x of list) {
        const k = x.d.rung.engagementId!
        m.set(k, [...(m.get(k) ?? []), x])
      }
      for (const v of m.values()) v.sort((a, b) => a.d.period.start.getTime() - b.d.period.start.getTime())
      return [...m.values()]
    }
    await ctx.parallel(
      byEngagement([...[...due.values()].map((d) => ({ d, ended: false })), ...ended.map((d) => ({ d, ended: true }))]),
      async (queue) => {
        for (const x of queue) await bill(x.d, x.ended)
      }
    )

    // The twin's sent drafts are bills too.
    const twinBills = await ctx.read.invoice.findMany({
      where: { id: { in: drafts.map((d) => d.id) }, status: { notIn: ['DRAFT', 'CANCELLED', 'VOID'] } },
      select: { id: true, total: true, engagementId: true, status: true },
    })
    for (const b of twinBills) {
      if (ctx.world.bills.some((x) => x.id === b.id)) continue
      const live = placements.flatMap((p) => p.ladder.map((r) => ({ r, p, ended: false })))
      const gone = endedUnbilled.flatMap((p) => p.ladder.map((r) => ({ r, p, ended: true })))
      const rung = [...live, ...gone].find(({ r }) => r.engagementId === b.engagementId)
      if (!rung) continue
      ctx.world.bills.push({
        id: b.id, by: 'twin', fromSlug: rung.r.sellerSlug, toSlug: rung.r.buyerSlug, totalCents: centsOf(b.total), status: b.status,
        extra: { placementId: rung.p.id, sellId: rung.r.sellId, twin: true, ended: rung.ended },
      })
    }
    for (const b of ctx.world.bills) totalCents += b.totalCents

    // What the ended placements' weeks came to on bills, the twin's and ours.
    const endedSays: string[] = []
    for (const [sellId, owed] of owedOnEnded) {
      const lines = await ctx.read.invoiceLine.findMany({
        where: { sellContractId: sellId, timesheetId: { in: owed.ids }, invoice: { status: { notIn: ['DRAFT', 'CANCELLED', 'VOID'] } } },
        select: { timesheetId: true, amountCents: true },
      })
      const weeks = new Set(lines.map((l) => l.timesheetId)).size
      const got = lines.reduce((n, l) => n + l.amountCents, 0)
      endedSays.push(`${owed.name}: ${weeks} of ${owed.ids.length} signed weeks on a sent bill, ${dollars(got)} of ${dollars(owed.cents)} owed.`)
    }

    // ── Checked against the record: each rung bills the hours its payer accepted ──
    const mismatches: string[] = []
    let checked = 0
    const billLines = await ctx.read.invoiceLine.findMany({
      where: { invoiceId: { in: ctx.world.bills.map((b) => b.id) }, timesheetId: { in: ctx.world.weeks.map((w) => w.id) } },
      select: { timesheetId: true, sellContractId: true, hours: true, amountCents: true, rateCents: true },
    })
    for (const l of billLines) {
      const w = ctx.world.weeks.find((x) => x.id === l.timesheetId)
      const p = w && placements.find((q) => q.id === w.contractId)
      if (!w || !p) continue
      const i = p.ladder.findIndex((r) => r.sellId === l.sellContractId)
      if (i < 0) continue
      const x = weekExtra(w)
      const payer = p.ladder[i].buyerId
      const accepted = i === 0 ? null : x.accepted?.[payer]
      const expected = accepted ?? w.hours
      checked++
      if (Math.abs(Number(l.hours) - expected) > 0.001) {
        mismatches.push(
          `${p.personName}'s week of ${w.weekStart} is billed by ${p.ladder[i].sellerName} for ${Number(l.hours)} hours where ${p.ladder[i].buyerName} ${accepted != null ? `accepted ${accepted}` : `signed ${w.hours}`}.`
        )
      }
    }
    for (const m of mismatches.slice(0, 10)) ctx.log(`money fault: ${m}`)
    // The expenses the firms above accepted, riding the bills as lines of their own.
    const expenseLines = await ctx.read.invoiceLine.findMany({
      where: { invoiceId: { in: ctx.world.bills.map((b) => b.id) }, expenseId: { in: ctx.world.expenses.map((e) => e.id) } },
      select: { amountCents: true },
    })
    const expenseCents = expenseLines.reduce((n, l) => n + l.amountCents, 0)
    // The weeks a firm in the middle accepted short, as their supplier billed them.
    const cuts: string[] = []
    for (const l of billLines) {
      const w = ctx.world.weeks.find((x) => x.id === l.timesheetId)
      const p = w && placements.find((q) => q.id === w.contractId)
      if (!w || !p) continue
      const i = p.ladder.findIndex((r) => r.sellId === l.sellContractId)
      const accepted = i > 0 ? weekExtra(w).accepted?.[p.ladder[i].buyerId] : null
      if (accepted == null || accepted === w.hours) continue
      cuts.push(
        `${p.personName}'s week of ${w.weekStart}: ${w.hours} hours worked, ${accepted} accepted by ${p.ladder[i].buyerName}, ` +
          `billed by ${p.ladder[i].sellerName} as ${Number(l.hours)} hours at ${dollars(l.rateCents)} = ${dollars(l.amountCents)}.`
      )
    }

    // ── The rule, held on purpose: a week nobody signed is not billed ────
    const unsigned = ctx.world.weeks.find((w) => weekExtra(w).unsigned)
    const pu = unsigned && placements.find((p) => p.id === unsigned.contractId)
    if (unsigned && pu && pu.ladder[0].engagementId) {
      const seat = await seatWith(ctx, pu.ladder[0].sellerId, 'invoices.issue', [pu.personId])
      if (seat) {
        await ctx.expectRefusal(
          seat,
          (a) => a.post('/api/invoices/generate', {
            engagementId: pu.ladder[0].engagementId, periodStart: unsigned.weekStart, periodEnd: weekExtra(unsigned).periodEnd,
          }),
          /waiting for .* to sign|nothing to bill/
        )
      }
    }

    return {
      closed: sent,
      of: due.size + ended.length,
      says: says([
        `${made} bills generated and ${sent} sent, one per billing period per rung, ${dollars(totalCents)} billed in all (USD), ${twinSent} of them drafted by the supplier's twin and sent on a yes.`,
        owedOnEnded.size
          ? `Placements that had ended with signed weeks nobody billed (Karthik Menon's case), ${endedBills} bills raised by hand for ${dollars(endedCents)}, the rest by the twin: ${endedSays.join(' ')}`
          : 'No ended placement had signed weeks left unbilled.',
        expenseLines.length ? `${expenseLines.length} accepted expenses rode the bills as lines of their own, ${dollars(expenseCents)}.` : 'No accepted expense rode a bill.',
        cuts.length ? `Weeks accepted short in the middle of a chain, as billed: ${cuts.slice(0, 3).join(' ')}` : null,
        notYet.size ? `${notYet.size} billing periods are still running, so their weeks wait for the bill on the agreement's date.` : null,
        `${checked - mismatches.length} of ${checked} billed weeks priced exactly the hours the firm above signed or accepted${mismatches.length ? `; ${mismatches.length} did not, and each is a money fault in the log` : ''}.`,
      ]),
    }
  },
})
